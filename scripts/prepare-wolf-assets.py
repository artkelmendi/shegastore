"""Copy approved vector artwork; derive animation layers without redrawing it."""
from pathlib import Path
import json
import re
import shutil

root = Path(__file__).resolve().parent.parent
source = root.parent / 'outputs' / 'wolf-shop'
target = root / 'public' / 'logos'
assets = {
    'wolf-full-light.svg': '02-full-logo/black-red-eyes/wolf-shop-full-black-red-eyes.svg',
    'wolf-full-dark.svg': '02-full-logo/white-red-eyes/wolf-shop-full-white-red-eyes.svg',
    'wolf-ticket-light.svg': '03-ticket-only/black-red-eyes/wolf-shop-ticket-black-red-eyes.svg',
    'wolf-ticket-dark.svg': '03-ticket-only/white-red-eyes/wolf-shop-ticket-white-red-eyes.svg',
    'wolf-ticket-red.svg': '03-ticket-only/red/wolf-shop-ticket-red.svg',
    'wolf-text-light.svg': '04-text-only/black/wolf-shop-text-black.svg',
    'wolf-text-dark.svg': '04-text-only/white/wolf-shop-text-white.svg',
}
for filename, original in assets.items():
    shutil.copyfile(source / original, target / filename)
svg = (source / assets['wolf-full-light.svg']).read_text(encoding='utf-8')
markup = re.search(r'<svg\b[^>]*>(.*)</svg>', svg, re.S).group(1)
markup = markup.replace('id="Complete_symmetrical_ticket"', 'class="wolf-ticket-ink"')
markup = markup.replace('id="WOLF_SHOP_lettering"', 'class="wolf-lettering"')
markup = re.sub(r'<polygon\b', '<polygon class="wolf-eye"', markup, count=2)
markup = re.sub(r'<(path|polygon)\b', r'<\1 pathLength="1"', markup)
wordmark_svg = (source / assets['wolf-text-light.svg']).read_text(encoding='utf-8')
wordmark = re.search(r'<svg\b[^>]*>(.*)</svg>', wordmark_svg, re.S).group(1)
wordmark = wordmark.replace('id="WOLF_SHOP_lettering"', 'class="wolf-lettering"')
wordmark = re.sub(r'\s+id="[^"]+"', '', wordmark)
wordmark = re.sub(r'<(path|polygon)\b', r'<\1 pathLength="1"', wordmark)
(root / 'src' / 'wolf-artwork.js').write_text('// Approved Wolf Shop vectors; generated by scripts/prepare-wolf-assets.py.\nexport const wolfMarkup = ' + json.dumps(markup) + ';\nexport const wolfWordmarkMarkup = ' + json.dumps(wordmark) + ';\n', encoding='utf-8')
for old, new in [('shega-boss-hero', 'wolf-boss-hero'), ('shega-armani-hero', 'wolf-armani-hero'), ('shega-boss-editorial', 'wolf-boss-editorial')]:
    previous = root / 'public' / 'images' / 'real' / (old+'.webp')
    current = root / 'public' / 'images' / 'real' / (new+'.webp')
    if previous.exists():
        shutil.copyfile(previous, current)
    elif not current.exists():
        raise FileNotFoundError(f'Missing original image: {current}')
print('Prepared seven original Wolf SVG assets and the layered animation artwork.')
